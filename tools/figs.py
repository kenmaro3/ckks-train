#!/usr/bin/env python3
"""Generate standalone SVG and native TeX figures from validated paper-table cells.

Only the Python standard library is needed. Source JSON is read, never rewritten.
The existing table generator owns validation and the four RQ1 definitions; this
module only selects measured subset rows and renders their already-rounded cells.
"""
import argparse
import hashlib
import html
import json
import math
from pathlib import Path
import sys

sys.path.insert(0, str(Path(__file__).resolve().parent))
import paper_tables as tables

REPO = Path(__file__).resolve().parents[1]


class FigureError(ValueError):
    """A required measured input is absent or invalid."""


def figure_data(root):
    root = Path(root)
    try:
        store = tables.Store(root)
        table = tables.table_rq1(store, tables.Inputs(store))
        rows, sources = [], {}
        for kind, cells in table.rows:
            if kind != 'row' or cells[0].text not in ('F1', 'F2'):
                continue
            if any(c.text == 'pending' for c in cells[9:13]):
                raise FigureError(f'{cells[0].text}: measured subset missing')
            if cells[1].text != '784' or cells[4].text != 'faithful':
                raise FigureError('figure requires the faithful 784-input subset')
            ratios = [float(c.text) for c in cells[9:13]]
            if not all(math.isfinite(x) and 0 <= x <= 1 for x in ratios):
                raise FigureError('ratios outside plotted [0,1] interval')
            rows.append({'run': cells[0].text, 'batch': int(cells[3].text), 'ratios': ratios})
            for cell in cells[9:13]:
                for rel, field in cell.sources:
                    sources.setdefault(rel, set()).add(field)
        if len(rows) != 2:
            raise FigureError('both faithful measured subset rows are required')
        return {
            'scope': 'supplementary 784-input subset; one seed per row',
            'ways': ['a', 'b', 'c', 'd'],
            'threshold': tables.GATE_KS,
            'precision': 'three decimal places, identical to generated RQ1 table cells',
            'rows': rows,
            'sources': [
                {'path': rel, 'sha256': hashlib.sha256((root / rel).read_bytes()).hexdigest(),
                 'fields': sorted(fields)} for rel, fields in sorted(sources.items())
            ],
        }
    except (tables.TableError, OSError, ValueError, KeyError, TypeError) as exc:
        raise FigureError(str(exc)) from exc


def render(data):
    colors = ['315C8C', '487F9C', '6C9B8B', 'A2A76B']
    tex = [
        '% Generated by tools/figs.py; do not edit. See rq1_ratios.sources.json.',
        r'\begin{figure}[t]', r'\centering', r'\setlength{\unitlength}{1pt}',
        r'\begin{picture}(240,143)',
        r'\put(28,32){\line(1,0){204}}', r'\put(28,32){\line(0,1){82}}',
        r'\put(5,124){\makebox(225,10){\footnotesize KS ratio to ReBoot (lower is better)}}',
    ]
    svg = ['<svg xmlns="http://www.w3.org/2000/svg" width="500" height="300" viewBox="0 0 500 300">',
           '<title>RQ1 supplementary subset key-switch ratios</title>',
           '<desc>One seed per row. Four counting conventions use measured hekit counters and modeled baseline bootstrap costs; not equal-security validation.</desc>',
           '<rect width="500" height="300" fill="white"/>',
           '<g font-family="sans-serif" font-size="12" fill="#182633">',
           '<text x="250" y="20" text-anchor="middle">KS ratio to ReBoot (lower is better)</text>',
           '<text x="250" y="290" text-anchor="middle">supplementary 784-input subset; one seed per row</text>']
    for tick in (0, .25, .5, .75, 1):
        y = 32 + 80*tick
        tex.append(fr'\put(25,{y:.2f}){{\line(1,0){{3}}}}')
        tex.append(fr'\put(0,{y-3:.2f}){{\makebox(22,7)[r]{{\tiny {tick:g}}}}}')
        sy = 240 - 160*tick
        svg.append(f'<line x1="55" x2="475" y1="{sy}" y2="{sy}" stroke="#dbe1e5"/>')
        svg.append(f'<text x="47" y="{sy+4}" text-anchor="end">{tick:g}</text>')
    threshold = data['threshold']
    y = 32 + 80*threshold
    tex += [fr'\multiput(28,{y:.2f})(5,0){{41}}{{\line(1,0){{2}}}}',
            fr'\put(176,{y+3:.2f}){{\makebox(55,7)[r]{{\tiny threshold {threshold:g}}}}}']
    sy = 240-160*threshold
    svg += [f'<line x1="55" x2="475" y1="{sy}" y2="{sy}" stroke="#182633" stroke-dasharray="5 4"/>',
            f'<text x="475" y="{sy-7}" text-anchor="end">threshold {threshold:g}</text>']
    for group, row in enumerate(data['rows']):
        for idx, (way, value) in enumerate(zip(data['ways'], row['ratios'])):
            x = 42 + group*103 + idx*19
            h = 80*value
            tex += [fr'\put({x},32){{\color[HTML]{{{colors[idx]}}}\rule{{14pt}}{{{h:.3f}pt}}}}',
                    fr'\put({x-4},{34+h:.3f}){{\makebox(22,7){{\tiny {value:.3f}}}}}',
                    fr'\put({x},21){{\makebox(14,7){{\scriptsize ({way})}}}}']
            sx=2*x; sh=160*value
            svg += [f'<rect x="{sx}" y="{240-sh:.3f}" width="28" height="{sh:.3f}" fill="#{colors[idx]}"/>',
                    f'<text x="{sx+14}" y="{234-sh:.3f}" text-anchor="middle">{value:.3f}</text>',
                    f'<text x="{sx+14}" y="255" text-anchor="middle">({html.escape(way)})</text>']
        label=f'{row["run"]}: B = {row["batch"]}'
        tex.append(fr'\put({35+103*group},6){{\makebox(90,10){{\footnotesize {label}}}}}')
        svg.append(f'<text x="{146+206*group}" y="274" text-anchor="middle">{html.escape(label)}</text>')
    tex += [r'\end{picture}',
            r'\caption{Supplementary subset RQ1 ratios (one seed per row), generated from the same cells as Table~\ref{tab:rq1_ks}. Bars (a)--(d) denote the four accounting conventions in Section~\ref{sec:evaluation}. These are not equal-security or full-setting results.}',
            r'\Description{Grouped bars for the two faithful subset batches under four key-switch accounting conventions. The larger batch is below the threshold in all four; the smaller batch only under own bootstrap costs. One seed per row; not an equal-security comparison.}',
            r'\label{fig:rq1-ratios}', r'\end{figure}', '']
    svg += ['</g></svg>', '']
    return '\n'.join(tex), '\n'.join(svg)


def main(argv=None):
    parser=argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--root', type=Path, default=REPO)
    parser.add_argument('--out', type=Path, default=REPO/'paper/figs')
    parser.add_argument('--check', action='store_true', help='check generated artifacts without writing')
    args=parser.parse_args(argv)
    try:
        data=figure_data(args.root)
        tex,svg=render(data)
        outputs={'rq1_ratios.tex':tex,'rq1_ratios.svg':svg,
                 'rq1_ratios.sources.json':json.dumps(data,indent=2,sort_keys=True)+'\n'}
        if args.check:
            stale=[name for name,value in outputs.items() if not (args.out/name).is_file() or (args.out/name).read_text()!=value]
            if stale:
                raise FigureError('stale or missing: '+', '.join(stale))
        else:
            args.out.mkdir(parents=True,exist_ok=True)
            for name,value in outputs.items():
                (args.out/name).write_text(value)
        print(('checked' if args.check else 'wrote')+f' {len(outputs)} figure artifacts; raw results unchanged')
        return 0
    except FigureError as exc:
        print(f'figure error: {exc}',file=sys.stderr)
        return 1


if __name__=='__main__':
    raise SystemExit(main())

//! Parameter-only exact scale evidence and a separately scoped insecure runtime fixture.
use ckks_train_ckks::metadata::{
    CtMeta, exact_product_scale_at, scalar_metadata_at, target_plain_scale_at,
};
use ckks_train_ckks::{CkksParams, Evaluator, HeOps};

#[test]
fn secure_parameter_metadata_uses_actual_q_and_exact_bits() {
    // Construct parameter tables only: no key generation, ciphertexts or Encoder.
    for params in [CkksParams::n16_train(), CkksParams::n16_boot()] {
        let delta = params.scale();
        let mut recurrence = delta;
        for level in (1..=params.max_level()).rev() {
            let q = params.q()[level] as f64;
            for exponent in [20, 42, 80] {
                let target = 2f64.powi(exponent);
                let label = exact_product_scale_at(&params, level, target).unwrap();
                assert_eq!(label.to_bits(), (target * q).to_bits());
                assert_eq!((label / q).to_bits(), target.to_bits());
            }
            // A target generated by actual runtime multiply-then-divide arithmetic is reachable.
            let product = recurrence * delta;
            let target = product / q;
            let label = exact_product_scale_at(&params, level, target).unwrap();
            assert_eq!((label / q).to_bits(), target.to_bits());
            let source = CtMeta::new(&params, level, delta).unwrap();
            let meta = scalar_metadata_at(&params, source, -0.125, delta).unwrap();
            assert_eq!(meta.pre_rescale().level(), level);
            assert_eq!(meta.pre_rescale().scale_bits(), (delta * q).to_bits());
            assert_eq!(meta.plain_scale().to_bits(), q.to_bits());
            assert_eq!(meta.rounded_integer(), (-0.125 * q).round());
            assert_eq!(meta.post_rescale().level(), level - 1);
            assert_eq!(meta.post_rescale().scale_bits(), delta.to_bits());
            recurrence = target;
        }
    }
}

#[test]
fn public_helpers_match_existing_evaluator_without_execution() {
    let params = std::sync::Arc::new(CkksParams::new(4, &[50, 30, 30], &[50], 30, 3).unwrap());
    let ev = Evaluator::new(params.clone(), None, None);
    let target = params.scale();
    assert_eq!(
        exact_product_scale_at(&params, 2, target)
            .unwrap()
            .to_bits(),
        ev.exact_product_scale(2, target).unwrap().to_bits()
    );
    assert_eq!(
        target_plain_scale_at(&params, 2, target, target).unwrap(),
        params.q()[2] as f64
    );
    assert_eq!(HeOps::counter(&ev), Default::default());
}

use ckks_train_core::error::{HekitError, Result};

fn invalid<T: std::fmt::Debug>(result: Result<T>) {
    assert!(
        matches!(result, Err(HekitError::InvalidParams(_))),
        "{result:?}"
    );
}

fn small_params() -> CkksParams {
    CkksParams::new(4, &[50, 30, 30], &[50], 30, 3).unwrap()
}

#[test]
fn exact_labels_agree_with_independent_local_scan_and_fixed_unreachable_target() {
    let params = CkksParams::new(12, &[60, 20, 20], &[60], 20, 3).unwrap();
    assert_eq!(params.q()[1..], [974_849, 1_032_193]);
    // Fixed counterexample, found independently by scanning +/-32 neighboring labels.
    let unreachable = f64::from_bits(0x4135_eb85_1eb8_aeb9);
    let q = 974_849.0;
    let center = (unreachable * q).to_bits();
    assert!((center - 32..=center + 32).all(|bits| f64::from_bits(bits) / q != unreachable));
    assert_eq!(
        exact_product_scale_at(&params, 1, unreachable),
        Err(HekitError::ScaleMismatch)
    );
    assert_eq!(
        target_plain_scale_at(&params, 1, params.scale(), unreachable),
        Err(HekitError::ScaleMismatch)
    );
    let source = CtMeta::new(&params, 1, params.scale()).unwrap();
    assert_eq!(
        scalar_metadata_at(&params, source, 1.0, unreachable),
        Err(HekitError::ScaleMismatch)
    );
    for level in 1..=2 {
        let q = params.q()[level] as f64;
        for offset in 0..200u64 {
            let target = f64::from_bits(0x4135_eb85_1eb8_51ec + offset * 7919);
            let center = (target * q).to_bits();
            let candidates: Vec<_> = (center - 32..=center + 32)
                .filter(|&b| f64::from_bits(b) / q == target)
                .collect();
            match exact_product_scale_at(&params, level, target) {
                Ok(label) => {
                    assert!(candidates.contains(&label.to_bits()));
                    let nearest = candidates
                        .iter()
                        .min_by_key(|&&b| (b.abs_diff(center), b < center))
                        .unwrap();
                    assert_eq!(label.to_bits(), *nearest);
                }
                Err(error) => {
                    assert_eq!(error, HekitError::ScaleMismatch);
                    assert!(candidates.is_empty());
                }
            }
        }
    }
}

#[test]
fn source_level_target_and_overflow_checks_use_typed_errors() {
    let params = small_params();
    let delta = params.scale();
    for source in [0.0, -0.0, -1.0, f64::NAN, f64::INFINITY, f64::NEG_INFINITY] {
        invalid(CtMeta::new(&params, 1, source));
        invalid(target_plain_scale_at(&params, 1, source, delta));
    }
    let zero = CtMeta::new(&params, 0, delta).unwrap();
    assert_eq!(zero.scale_bits(), delta.to_bits());
    assert_eq!(
        exact_product_scale_at(&params, 0, delta),
        Err(HekitError::NoLevelsLeft)
    );
    assert_eq!(
        target_plain_scale_at(&params, 0, delta, delta),
        Err(HekitError::NoLevelsLeft)
    );
    assert_eq!(
        scalar_metadata_at(&params, zero, 1.0, delta),
        Err(HekitError::NoLevelsLeft)
    );
    let bad_level = params.max_level() + 1;
    invalid(CtMeta::new(&params, bad_level, delta));
    invalid(exact_product_scale_at(&params, bad_level, delta));
    invalid(target_plain_scale_at(&params, bad_level, delta, delta));
    let source = CtMeta::new(&params, 2, delta).unwrap();
    for target in [
        0.0,
        -1.0,
        f64::NAN,
        f64::INFINITY,
        f64::NEG_INFINITY,
        f64::MAX,
    ] {
        invalid(exact_product_scale_at(&params, 2, target));
        invalid(target_plain_scale_at(&params, 2, delta, target));
        invalid(scalar_metadata_at(&params, source, 1.0, target));
    }
    for value in [f64::NAN, f64::INFINITY, f64::NEG_INFINITY, f64::MAX] {
        invalid(scalar_metadata_at(&params, source, value, delta));
    }
    // A receipt is rechecked against the actual parameters on every scalar call.
    let shorter = CkksParams::new(4, &[50], &[50], 30, 1).unwrap();
    invalid(scalar_metadata_at(&shorter, source, 1.0, delta));
    // Exact-product helper preserves legacy level/target error precedence.
    invalid(exact_product_scale_at(&params, 0, f64::NAN));
    invalid(scalar_metadata_at(&params, zero, f64::NAN, delta));
}

#[test]
fn scalar_minimum_integer_threshold_and_rounded_zero_are_exact() {
    let params = small_params();
    let target = params.scale();
    let label = target * params.q()[2] as f64;
    // Exact powers of two make these minimum and integer boundaries independent of search.
    let source = CtMeta::new(&params, 2, label / 2f64.powi(20)).unwrap();
    assert_eq!(
        target_plain_scale_at(&params, 2, source.scale(), target).unwrap(),
        2f64.powi(20)
    );
    for value in [
        0.0,
        -0.0,
        -1.25,
        0.25 / 2f64.powi(20),
        -0.25 / 2f64.powi(20),
    ] {
        let receipt = scalar_metadata_at(&params, source, value, target).unwrap();
        let k = (value * 2f64.powi(20)).round();
        assert_eq!(receipt.rounded_integer().to_bits(), k.to_bits());
        assert_eq!(
            receipt.represented_value().to_bits(),
            (k / 2f64.powi(20)).to_bits()
        );
    }
    let tiny = CtMeta::new(&params, 2, label / 2f64.powi(19)).unwrap();
    invalid(target_plain_scale_at(&params, 2, tiny.scale(), target));
    invalid(scalar_metadata_at(&params, tiny, 0.0, target));
    for sign in [-1.0, 1.0] {
        invalid(scalar_metadata_at(
            &params,
            source,
            sign * 2f64.powi(42),
            target,
        ));
        let inside = sign * f64::from_bits(2f64.powi(42).to_bits() - 1);
        let receipt = scalar_metadata_at(&params, source, inside, target).unwrap();
        assert!(receipt.rounded_integer().abs() < 2f64.powi(62));
    }
}


#[test]
fn insecure_runtime_scalar_matches_receipt_actual_value_and_counts() {
    use ckks_train_ckks::{Decryptor, Encoder, Encryptor, KeyGenerator, OpCounter};
    use ckks_train_core::sampler::Rng;
    use std::sync::Arc;

    // Deliberately insecure N=16 fixture; not a scientific profile or secure key run.
    let params = Arc::new(small_params());
    let keygen = KeyGenerator::new(params.clone(), Rng::from_seed([154; 32])).unwrap();
    let sk = keygen.secret_key();
    let encoder = Encoder::new(params.clone());
    let encryptor = Encryptor::with_secret_key(params.clone(), sk.clone());
    let decryptor = Decryptor::new(params.clone(), sk);
    let ev = Evaluator::new(params.clone(), None, None);
    let values = [0.125, -0.25, 0.5, -0.75, 0.0, 0.25, -0.125, 0.375];
    let pt = encoder.encode(&values, params.scale(), 2).unwrap();
    let ct = encryptor.encrypt(&pt, &mut Rng::from_seed([155; 32]));
    let source = CtMeta::new(&params, ct.level(), ct.scale()).unwrap();
    for value in [0.0, -0.0, -1.25, 0.1, 0.25 / params.q()[2] as f64] {
        ev.reset_counter();
        let receipt = scalar_metadata_at(&params, source, value, params.scale()).unwrap();
        let sp =
            target_plain_scale_at(&params, source.level(), source.scale(), params.scale()).unwrap();
        assert_eq!(
            sp.to_bits(),
            ev.target_plain_scale(&ct, params.scale())
                .unwrap()
                .to_bits()
        );
        assert_eq!(
            sp.to_bits(),
            HeOps::target_plain_scale(&ev, &ct, params.scale())
                .unwrap()
                .to_bits()
        );
        assert_eq!(
            receipt.pre_rescale().scale_bits(),
            HeOps::exact_product_scale(&ev, 2, params.scale())
                .unwrap()
                .to_bits()
        );
        assert_eq!(
            ev.counter(),
            OpCounter::default(),
            "metadata does not count operations"
        );
        let product = ev.mul_scalar(&ct, value, params.scale()).unwrap();
        assert_eq!(
            (product.level(), product.scale().to_bits()),
            (
                receipt.pre_rescale().level(),
                receipt.pre_rescale().scale_bits()
            )
        );
        assert_eq!(
            ev.counter(),
            OpCounter {
                ct_pt_mults: 1,
                ..Default::default()
            }
        );
        let output = ev.rescale(&product).unwrap();
        assert_eq!(
            (output.level(), output.scale().to_bits()),
            (
                receipt.post_rescale().level(),
                receipt.post_rescale().scale_bits()
            )
        );
        assert_eq!(
            ev.counter(),
            OpCounter {
                ct_pt_mults: 1,
                rescales: 1,
                ..Default::default()
            }
        );
        let decoded = encoder.decode(&decryptor.decrypt(&output));
        for (got, input) in decoded.iter().zip(values) {
            assert!(
                (got - input * receipt.represented_value()).abs() < 1e-6,
                "{got} vs {input} * {}",
                receipt.represented_value()
            );
        }
        assert_eq!(
            receipt.rounded_integer(),
            (value * (params.q()[2] as f64)).round()
        );
    }
    // Normal-domain failures preserve the runtime's typed error and message order.
    for value in [f64::NAN, f64::INFINITY, f64::MAX] {
        assert_eq!(
            scalar_metadata_at(&params, source, value, params.scale()).unwrap_err(),
            ev.mul_scalar(&ct, value, params.scale()).unwrap_err()
        );
    }
    for target in [
        0.0,
        f64::NAN,
        f64::MAX,
        params.scale() * 2f64.powi(19) / params.q()[2] as f64,
    ] {
        assert_eq!(
            scalar_metadata_at(&params, source, 0.5, target).unwrap_err(),
            ev.mul_scalar(&ct, 0.5, target).unwrap_err()
        );
    }
}

#[test]
fn legacy_tiny_source_zero_scalar_behavior_is_characterized_separately() {
    use ckks_train_ckks::{Ciphertext, OpCounter};
    use ckks_train_core::poly::RnsPoly;
    use std::sync::Arc;

    let params = Arc::new(small_params());
    let ev = Evaluator::new(params.clone(), None, None);
    let mut zero = RnsPoly::zero(params.basis_q(), 2);
    zero.to_ntt();
    let ct = Ciphertext::new(vec![zero.clone(), zero], f64::from_bits(1)).unwrap();
    assert_eq!(
        ev.target_plain_scale(&ct, params.scale()).unwrap(),
        f64::INFINITY
    );
    assert_eq!(
        HeOps::target_plain_scale(&ev, &ct, params.scale()).unwrap(),
        f64::INFINITY
    );
    assert_eq!(ev.counter(), OpCounter::default());
    let product = ev.mul_scalar(&ct, 0.0, params.scale()).unwrap();
    assert_eq!(product.scale(), params.scale() * params.q()[2] as f64);
    assert_eq!(
        ev.counter(),
        OpCounter {
            ct_pt_mults: 1,
            ..Default::default()
        }
    );
    let source = CtMeta::new(&params, 2, ct.scale()).unwrap();
    invalid(target_plain_scale_at(
        &params,
        2,
        ct.scale(),
        params.scale(),
    ));
    invalid(scalar_metadata_at(&params, source, 0.0, params.scale()));
    assert_eq!(
        ev.counter(),
        OpCounter {
            ct_pt_mults: 1,
            ..Default::default()
        }
    );
}
